#!/bin/bash
# atlas-pointer.sh <repo> — write the atlas back-reference block into a repo's
# CLAUDE.md, so an agent reading the repo cold learns the machine-wide wiki
# exists and how to query it.
#
# CLAUDE.md is canonical; AGENTS.md is a symlink to it (atlas-onboard step 0),
# so it mirrors this content dynamically and needs no separate write.
#
# Marker-delimited and idempotent, matching the convention gitnexus and
# OpenWiki already use in these same files (<!-- gitnexus:start -->,
# <!-- OPENWIKI:START -->). Only the region between the markers is ever
# rewritten; everything else in CLAUDE.md is left byte-identical.
set -euo pipefail
repo="$(cd "${1:?usage: atlas-pointer.sh <repo>}" && pwd)"
name="$(basename "$repo")"
f="$repo/CLAUDE.md"

# A repo with no CLAUDE.md gets a minimal one — the pointer is worthless if
# there is no file an agent will read. Deliberately bare: atlas documents the
# machine, the repo's own docs are the repo's business.
if [[ ! -f $f ]]; then
  printf '# %s\n' "$name" > "$f"
  [[ -e "$repo/AGENTS.md" ]] || ln -s CLAUDE.md "$repo/AGENTS.md"
  echo "atlas-pointer: created $f (+ AGENTS.md symlink)"
fi

# Only advertise the sibling wikis that actually exist in this repo, as the qmd
# query that reaches them. Naming the folder alone got openwiki zero reads in 30
# days (2026-11-15): agents never went looking. Every harness here runs qmd.
extra=""
[[ -d "$repo/openwiki" ]] && extra+=$'\n'"qmd query -c repo-openwiki \"$name <topic>\"  # how it works now (generated from code)"
[[ -d "$repo/almanac" ]] && extra+=$'\n'"qmd query -c repo-almanac \"$name <topic>\"   # why it was built this way"

# ponytail: block lives in a file, not an awk -v. BSD awk (the macOS default)
# rejects newlines inside a -v assignment ("awk: newline in string").
bf="$(mktemp)"
trap 'rc=$?; rm -f "$bf" || true; exit $rc' EXIT
cat > "$bf" <<EOF
<!-- atlas:start -->
## Atlas — machine-wide context

Atlas maps every repo, service and config dir on this machine. This one's entity
doc carries its role, stack, services, CI state, last commit, and what is
currently running out of it.

Query it when unfamiliar architecture or a past decision matters, not at
task start. Source code wins when it disagrees.

\`\`\`bash
qmd get atlas/repos/$name.md    # this repo's entity doc
qmd query "<topic>"             # search every repo/service/config on this machine$extra
\`\`\`

### What not to edit here

Three things in this repo are written by the machine, not by you:

- \`openwiki/\` — regenerated by the cascade (local model). A hand edit is not lost
  at once: it is lost on the next generation, without warning. Something missing?
  Fix it in the code or the docs and let it regenerate.
- \`almanac/\` — mined and auto-committed by CodeAlmanac. Your edits go **only**
  below its \`<!-- manual -->\` marker; everything above is rewritten.
- \`AGENTS.md\` — a symlink to \`CLAUDE.md\`: edit \`CLAUDE.md\`. The cascade swaps it
  for a real copy while generating and restores it afterwards, so a transient
  \`T\` in \`git status\` is that swap, not corruption.

The hooks (\`pre-commit\` = gitleaks, \`post-commit\` = this cascade) belong to atlas
and are shared by every repo on the machine: do not edit them here.

Atlas regenerates the entity doc from scans — hand-edits go below its
\`<!-- manual -->\` marker only.
<!-- atlas:end -->
EOF

# Both markers, exactly once each, before rewriting anything. The awk below sets
# skip=1 at start and only clears it at end, so a CLAUDE.md carrying a start with
# no end would silently delete everything after it. Same guard the openwiki splice
# in atlas-cascade.sh already carries, and not hypothetical: atlas's own CLAUDE.md
# was found on 2026-08-16 with one start and two ends (the AGENTS.md symlink tear,
# committed before anyone looked), which this rewrote into a clean block plus an
# orphaned tail. Refuse instead — a human can see a refusal, not a silent deletion.
c_start="$(grep -c '<!-- atlas:start -->' "$f" || true)"
c_end="$(grep -c '<!-- atlas:end -->' "$f" || true)"
# Exactly two shapes are sane: no block at all (append), or one clean pair
# (replace). Everything else — including a stray end with no start, which the
# append path would turn into a second end — is damage this must not compound.
if ! { (( c_start == 0 && c_end == 0 )) || (( c_start == 1 && c_end == 1 )); }; then
  echo "atlas-pointer: REFUSED $f — markers not a clean pair (start=$c_start end=$c_end)" >&2
  exit 1
fi

if (( c_start == 1 )); then
  tmp="$(mktemp)"
  awk -v bf="$bf" '
    /<!-- atlas:start -->/ { while ((getline l < bf) > 0) print l; close(bf); skip = 1; next }
    /<!-- atlas:end -->/   { skip = 0; next }
    !skip
  ' "$f" > "$tmp"
  # ponytail: cat > preserves the inode, so AGENTS.md (a symlink to this file)
  # and any hardlink stay wired up. mv would replace the inode and break them.
  cat "$tmp" > "$f"
  rm -f "$tmp"
  echo "atlas-pointer: refreshed block in $f"
else
  printf '\n' >> "$f"
  cat "$bf" >> "$f"
  echo "atlas-pointer: appended block to $f"
fi

# Adopt an AGENTS.md that openwiki left behind as a regular file. The `[[ -e ]]`
# guard above only creates the symlink where nothing exists at all, so a repo
# that openwiki reached first kept two files that then drifted: measured
# 2026-08-24, 36 of 42 onboarded repos disagreed with their own CLAUDE.md, and
# 35 carried the atlas block in CLAUDE.md only — leaving the wiki undiscoverable
# to every agent that reads AGENTS.md instead (Codex, opencode).
#
# Converting deletes a file, so three conditions must all hold first:
#   1. CLAUDE.md is a regular file — with the inverted convention (CLAUDE.md ->
#      AGENTS.md) both paths read the same bytes, so the loss check passes on a
#      pair that would become a symlink loop (media-tools, 2026-09-18);
#   2. every non-blank line of AGENTS.md already appears in CLAUDE.md, so the
#      symlink cannot lose content;
#   3. git tracks it, so the conversion is undoable with
#      `git checkout -- AGENTS.md`.
# Unmodified is deliberately NOT required: condition 2 already proves there is
# nothing to lose, and the cascade's swap leaves a real copy of CLAUDE.md behind
# whenever a run dies before restoring the symlink (2026-09-18: 21 of 34
# divergent repos were that leftover, and the clean-tree rule kept them so).
#
# ponytail: condition 2 compares line sets, not order or counts. An AGENTS.md
# holding the same lines shuffled reads as covered. Upgrade path if that ever
# matters: diff the two files properly instead.
#
# The OPENWIKI block is left out of condition 2 when CLAUDE.md carries its own:
# openwiki rewrites that block in AGENTS.md alone, so a newer wording there made
# the pair read as "has unique lines" forever (2026-10-07: addocu, OmniZenit,
# y-combinator-scraper). It is generated, and through the symlink the next
# openwiki run refreshes the copy in CLAUDE.md.
a="$repo/AGENTS.md"
if [[ -f $a && ! -L $a ]]; then
  ow_skip='/^$/!b'   # no-op sed program
  grep -q '<!-- OPENWIKI:START -->' "$f" && ow_skip='/<!-- OPENWIKI:START -->/,/<!-- OPENWIKI:END -->/d'
  if [[ -L $f ]]; then
    echo "atlas-pointer: AGENTS.md kept as a file — CLAUDE.md is a symlink (inverted convention)"
  elif sed "$ow_skip" "$a" | grep -vxF -f "$f" | grep -q '[^[:space:]]'; then
    echo "atlas-pointer: AGENTS.md kept as a file — it has lines CLAUDE.md does not"
  elif ! git -C "$repo" ls-files --error-unmatch AGENTS.md >/dev/null 2>&1; then
    echo "atlas-pointer: AGENTS.md kept as a file — untracked, convert by hand"
  else
    rm -f "$a"
    ln -s CLAUDE.md "$a"
    echo "atlas-pointer: AGENTS.md adopted as a symlink to CLAUDE.md"
  fi
fi
