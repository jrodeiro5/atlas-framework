#!/bin/bash
# new-folder-claude-md.sh <path> — writes canonical CLAUDE.md + AGENTS.md
# symlink for a folder just created under ~/dev. Called from the mkdir
# shell function in ~/.zshrc. Idempotent: no-op if CLAUDE.md already exists.
set -euo pipefail
dir="${1:?usage: new-folder-claude-md.sh <path>}"
name="$(basename "$dir")"

[[ -f "$dir/CLAUDE.md" ]] && exit 0

# nothing inside .git or a tool's dot-folder (.pi, .claude, .vscode…).
# rev-parse fails inside .git, so the guard below never sees it.
case "$dir/" in */.*/*) exit 0 ;; esac

# a subfolder of a repo whose root already has CLAUDE.md gets nothing.
# Every mkdir inside a repo was leaving a template copy that ended up committed.
top="$(git -C "$dir" rev-parse --show-toplevel 2>/dev/null || true)"
[[ -n "$top" && "$top" != "$dir" && -f "$top/CLAUDE.md" ]] && exit 0

cat > "$dir/CLAUDE.md" <<EOF
# $name

<!-- auto-generated by atlas on mkdir. Fill in Purpose below by hand: nothing
     fills it in for you, and \`atlas check\` fails while it says TODO.
     \`atlas-onboard $dir\` wires the wiki/almanac cascade once this is a git
     repo; it does not touch this section. -->

## Purpose

TODO

Karpathy/caveman/ponytail guidelines already apply globally via
\`~/.claude/CLAUDE.md\` — no need to restate them here.
EOF

ln -s CLAUDE.md "$dir/AGENTS.md"

# atlas back-reference — the same marker-delimited block every onboarded repo
# gets, so there is one wording to maintain instead of two that drift.
"$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/atlas-pointer.sh" "$dir"
echo "atlas: CLAUDE.md + AGENTS.md created in $dir"
